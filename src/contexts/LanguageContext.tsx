interface LanguageContextType {
  currentLanguage: SupportedLanguage;
  setLanguage: (lang: SupportedLanguage) => void;
  languageInfo: LanguageInfo;
  isRTL: boolean;
  t: (key: string, fallback?: string) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  // Default to English for new users, or load saved preference
  const [currentLanguage, setCurrentLanguage] = useState<SupportedLanguage>(() => {
    const saved = localStorage.getItem('omnicraft_lang') as SupportedLanguage;
    if (saved && LANGUAGES.some((l) => l.code === saved)) {
      return saved;
    }
    return 'en'; // Default English for new users as requested
  });

  const languageInfo = LANGUAGES.find((l) => l.code === currentLanguage) || LANGUAGES[0];
  const isRTL = languageInfo.dir === 'rtl';

  useEffect(() => {
    localStorage.setItem('omnicraft_lang', currentLanguage);
    document.documentElement.lang = currentLanguage;
    document.documentElement.dir = isRTL ? 'rtl' : 'ltr';
  }, [currentLanguage, isRTL]);

  const t = (key: string, fallback?: string): string => {
    const langDict = translations[currentLanguage];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    // Fallback to English, then Arabic, then provided fallback
    if (translations['en'] && translations['en'][key]) {
      return translations['en'][key];
    }
    if (translations['ar'] && translations['ar'][key]) {
      return translations['ar'][key];
    }
    return fallback || key;
  };

  return (
    <LanguageContext.Provider
      value={{
        currentLanguage,
        setLanguage: setCurrentLanguage,
        languageInfo,
        isRTL,
        t,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = (): LanguageContextType => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
